export function getPhraseText(
  phrase: CommunicationPhrase,
  lang: SupportedLanguage,
  konkaniScript: KonkaniScript = 'deva'
): string {
  if (lang === 'kok') {
    return konkaniScript === 'romi' ? phrase.translations.kok_romi : phrase.translations.kok_deva;
  }
  return phrase.translations[lang] || phrase.translations.en;
}
